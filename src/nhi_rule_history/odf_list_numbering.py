"""Deterministic ODF list labels, reconstructed the way LibreOffice draws them.

An ODT list paragraph can display a generated label (``1.``, ``(5)``, ``II.``)
that is not part of its character data.  This module reproduces those labels
from the document's list styles, list structure and continuation attributes,
following the LibreOffice Writer import and numbering rules:

* list identity: a root ``text:list`` opens a new list unless
  ``text:continue-list`` names a processed list or ``text:continue-numbering``
  continues the immediately preceding list of the same style; in documents
  generated by Microsoft Office it continues the last list of that style;
* counting: the paragraphs of one list form a number tree.  The first
  paragraph of a ``text:list-item`` is counted; later paragraphs, paragraphs
  after a nested list and ``text:list-header`` paragraphs are not.  A missing
  parent level becomes a phantom that counts when it has counted children,
  and the first child of an uncounted parent continues the previous subtree.
  ``text:start-value`` on an item, and a second sub-list in one item, restart;
* labels: prefix, the level number in its number format and suffix, or the
  ``num-list-format`` string; ``text:display-levels`` joins parent numbers.

For a document generated by Microsoft Office the label must also be the one
that office suite prints: the plain per-level counter model must give the
same numbers, the ODF 1.4 ``number:num-list-format`` string must equal the
prefix/suffix form, and a number format must render identically in both
suites for the value at hand.  A paragraph is labelled only when every rule
it depends on is implemented here; bullets, images, unknown number formats,
style overrides, consecutive numbering, paragraph-style numbering outside a
list, lists inside frames or notes and any other unimplemented feature make
the paragraph ``unsupported`` so the caller can fail closed.
"""

