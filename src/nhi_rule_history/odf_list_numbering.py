def _roman(value: int) -> str:
    parts: list[str] = []
    for amount, symbol in _ROMAN:
        while value >= amount:
            parts.append(symbol)
            value -= amount
    return "".join(parts)


def _letters(value: int, alphabet: str, synchronized: bool) -> str:
    if synchronized:
        return alphabet[(value - 1) % 26] * ((value - 1) // 26 + 1)
    digits: list[str] = []
    index = value - 1
    while True:
        digits.append(alphabet[index % 26])
        if index < 26:
            break
        index = (index - 26) // 26
    return "".join(reversed(digits))


def format_number(
    value: int, num_format: str, *, letter_sync: bool, word_compatible: bool
) -> str:
    """Render one level number the way LibreOffice does.

    ``word_compatible`` restricts every format to values that Microsoft Word
    renders identically; anything else raises ``ListNumberingUnsupported``.
    """

    if num_format == "1":
        if value < 0:
            raise ListNumberingUnsupported("number_negative")
        return str(value)
    if value < 1:
        raise ListNumberingUnsupported("number_below_one")
    if num_format in {"a", "A"}:
        alphabet = (
            "abcdefghijklmnopqrstuvwxyz"
            if num_format == "a"
            else "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
        )
        if word_compatible and not letter_sync and value > 26:
            # Word repeats letters (aa, bb); unsynchronized LibreOffice
            # letters continue aa, ab.
            raise ListNumberingUnsupported("number_format_range")
        return _letters(value, alphabet, letter_sync)
    if num_format in {"i", "I"}:
        if value > 3999:
            raise ListNumberingUnsupported("number_format_range")
        text = _roman(value)
        return text.lower() if num_format == "i" else text
    tables = {
        "甲, 乙, 丙, ...": _TIAN_GAN,
        "子, 丑, 寅, ...": _DI_ZI,
        "壹, 貳, 參, ...": _UPPER_ZH_TW,
        "一, 二, 三, ...": _LOWER_ZH,
    }
    table = tables.get(num_format)
    if table is not None:
        # Only the single-character values are reproduced; LibreOffice
        # switches to Arabic or composes numerals beyond them.
        if value > len(table):
            raise ListNumberingUnsupported("number_format_range")
        return table[value - 1]
    raise ListNumberingUnsupported("number_format_unsupported")


def _effective_list_format(level: _Level) -> str:
    """LibreOffice's list format string for one level."""

    if level.list_format is not None:
        return level.list_format
    shown = min(level.display_levels, level.level)
    placeholders = ".".join(
        f"%{level.level - shown + index + 1}%" for index in range(shown)
    )
    return level.prefix + placeholders + level.suffix


def _expand_list_format(
    template: str,
    level: int,
    numbers: Mapping[int, int],
    formats: Mapping[int, _Level],
    *,
    word_compatible: bool,
) -> tuple[str, tuple[int, ...]]:
    """Substitute ``%N%`` placeholders exactly as SwNumRule::MakeNumString."""

    out: list[str] = []
    used: list[int] = []
    position = 0
    while position < len(template):
        if template[position] != "%" or position + 2 >= len(template):
            out.append(template[position])
            position += 1
            continue
        if template.startswith("%10%", position):
            target, end = 10, position + 4
        elif (
            "1" <= template[position + 1] <= "9"
            and template[position + 2] == "%"
        ):
            target, end = int(template[position + 1]), position + 3
        else:
            out.append(template[position])
            position += 1
            continue
        if target > level:
            # There is no number for a deeper level: LibreOffice drops it.
            position = end
            continue
        target_format = formats.get(target)
        if target_format is None or target_format.kind != "number":
            raise ListNumberingUnsupported("list_format_level_undefined")
        if target_format.num_format == "":
            raise ListNumberingUnsupported("list_format_level_without_number")
        value = numbers.get(target)
        if value is None:
            raise ListNumberingUnsupported("list_format_level_without_number")
        out.append(
            "0"
            if value == 0
            else format_number(
                value,
                target_format.num_format,
                letter_sync=target_format.letter_sync,
                word_compatible=word_compatible,
            )
        )
        used.append(target)
        position = end
    return "".join(out), tuple(used)


