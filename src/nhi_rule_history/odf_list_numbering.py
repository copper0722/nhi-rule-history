class _Node:
    __slots__ = ("paragraph", "parent", "children", "number", "depth")

    def __init__(
        self, paragraph: _Paragraph | None, parent: "_Node | None"
    ) -> None:
        self.paragraph = paragraph
        self.parent = parent
        self.children: list[_Node] = []
        self.number = 0
        self.depth = -1 if parent is None else parent.depth + 1

    @property
    def phantom(self) -> bool:
        return self.paragraph is None and self.parent is not None


class _Tree:
    """One list's SwNumberTree: insertion with phantoms and validation."""

    def __init__(self, style: _ListStyle) -> None:
        self.style = style
        self.root = _Node(None, None)

    def add(self, paragraph: _Paragraph) -> _Node:
        parent = self.root
        for _ in range(paragraph.level):
            if not parent.children:
                parent.children.append(_Node(None, parent))
            parent = parent.children[-1]
        node = _Node(paragraph, parent)
        parent.children.append(node)
        return node

    def counted(self, node: _Node) -> bool:
        if node.paragraph is not None:
            return node.paragraph.counted
        if node.parent is None:
            return True
        # Phantoms count when they have counted children (count-phantoms).
        return self.has_counted_children(node)

    def counted_for_numbering(self, node: _Node) -> bool:
        if node.paragraph is None:
            return self.counted(node)
        level = self.style.levels.get(node.depth + 1)
        return node.paragraph.counted and level is not None and (
            level.kind != "number" or level.num_format != ""
        )

    def has_counted_children(self, node: _Node) -> bool:
        return any(
            self.counted_for_numbering(child) or self.has_counted_children(child)
            for child in node.children
        )

    def has_phantom_counted_parent(self, node: _Node) -> bool:
        parent = node.parent
        if parent is None:
            return False
        if parent.parent is None:
            return True
        if not parent.phantom:
            return self.counted(parent)
        return self.counted(parent) and self.has_phantom_counted_parent(parent)

    def start_value(self, node: _Node) -> int:
        paragraph = node.paragraph
        if (
            paragraph is not None
            and paragraph.restart
            and paragraph.restart_value is not None
        ):
            return paragraph.restart_value
        level = self.style.levels.get(node.depth + 1)
        return level.start if level is not None else 1

    def validate(self, parent: _Node) -> None:
        """SwNumberTreeNode::ValidateHierarchical, then the children."""

        children = parent.children
        if children:
            first = children[0]
            number = self.start_value(first)
            if not self.counted(first) and (
                not self.has_counted_children(first) or first.phantom
            ):
                number -= 1
            parent_counted = self.counted(parent) and (
                not parent.phantom or self.has_phantom_counted_parent(parent)
            )
            first_restarts = (
                first.paragraph is not None and first.paragraph.restart
            )
            if (
                not first_restarts
                and parent.parent is not None
                and not parent_counted
            ):
                siblings = parent.parent.children
                for previous in reversed(siblings[: siblings.index(parent)]):
                    if previous.children:
                        number = previous.children[-1].number
                        if self.counted(first) and (
                            not first.phantom
                            or self.has_phantom_counted_parent(first)
                        ):
                            number += 1
                        break
                    if self.counted(previous):
                        break
            first.number = number
            for child in children[1:]:
                if self.counted(child):
                    restarts = (
                        child.paragraph is not None and child.paragraph.restart
                    )
                    number = self.start_value(child) if restarts else number + 1
                child.number = number
        for child in children:
            self.validate(child)

    def vector(self, node: _Node) -> tuple[dict[int, int], bool]:
        """Level numbers on the path, and whether an ancestor is uncounted."""

        numbers: dict[int, int] = {}
        uncertain = False
        current: _Node | None = node
        while current is not None and current.parent is not None:
            numbers[current.depth + 1] = current.number
            if current is not node and (
                current.phantom or not self.counted(current)
            ):
                uncertain = True
            current = current.parent
        return numbers, uncertain


def _tree_numbers(
    paragraphs: list[_Paragraph], style: _ListStyle
) -> dict[int, tuple[dict[int, int], bool]]:
    tree = _Tree(style)
    nodes = [(paragraph, tree.add(paragraph)) for paragraph in paragraphs]
    tree.validate(tree.root)
    return {paragraph.order: tree.vector(node) for paragraph, node in nodes}


def _counter_numbers(
    paragraphs: list[_Paragraph], style: _ListStyle
) -> dict[int, dict[int, int]]:
    """The plain per-level counters of the producing office suite."""

    counters: dict[int, int] = {}
    result: dict[int, dict[int, int]] = {}
    for paragraph in paragraphs:
        level = paragraph.level + 1
        if paragraph.counted:
            level_style = style.levels.get(level)
            start = level_style.start if level_style is not None else 1
            if paragraph.restart_value is not None:
                value = paragraph.restart_value
            elif level in counters:
                value = counters[level] + 1
            else:
                value = start
            counters[level] = value
            for deeper in [key for key in counters if key > level]:
                del counters[deeper]
        result[paragraph.order] = dict(counters)
    return result


