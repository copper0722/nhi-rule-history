class ListNumberingUnsupported(Exception):
    """A list feature this module does not reproduce; carries a reason code."""

    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason


@dataclass(frozen=True)
class ListLabel:
    """How one paragraph is numbered.

    ``status`` is ``labelled`` (a label is drawn), ``unlabelled`` (the
    paragraph belongs to a list but draws no label) or ``unsupported``.
    ``export_prefix`` is what LibreOffice's plain-text export writes before
    the paragraph text: indentation, the label or a placeholder, and a space.
    """

    status: str
    label: str = ""
    separator: str = ""
    export_prefix: str = ""
    reason: str | None = None
    evidence: Mapping[str, Any] = field(default_factory=dict)

    @property
    def printed_prefix(self) -> str:
        """The generated text printed before the paragraph's own text."""

        if self.status != "labelled":
            return ""
        return self.label + self.separator


