def _label(
    paragraph: _Paragraph,
    vector: Mapping[int, int],
    uncertain_ancestor: bool,
    counters: Mapping[int, int] | None,
    styles: _Styles,
    *,
    mso: bool,
) -> ListLabel:
    style = paragraph.style
    level_number = paragraph.level + 1
    indent = EXPORT_INDENT * level_number
    if style is None:
        raise ListNumberingUnsupported("list_style_unresolved")
    level = style.levels.get(level_number)
    if level is None:
        raise ListNumberingUnsupported("list_level_undefined")
    if level.malformed:
        raise ListNumberingUnsupported(level.malformed)
    if level.kind != "number":
        raise ListNumberingUnsupported(f"{level.kind}_label")
    if level.is_legal:
        raise ListNumberingUnsupported("legal_numbering")
    evidence: dict[str, Any] = {
        "rule_version": LIST_LABEL_RULE_VERSION,
        "list_style": style.name,
        "list_style_origin": style.origin,
        "level": level_number,
        "num_format": level.num_format,
        "num_prefix": level.prefix,
        "num_suffix": level.suffix,
        "counted": paragraph.counted,
    }
    if not paragraph.counted:
        return ListLabel(
            status="unlabelled",
            export_prefix=indent + "  " + " ",
            evidence=evidence,
        )
    if level.num_format == "":
        if level.prefix or level.suffix or level.list_format:
            raise ListNumberingUnsupported("number_none_with_affixes")
        if mso:
            _check_word_format(level, styles, "")
        return ListLabel(
            status="unlabelled",
            export_prefix=indent + "  " + " ",
            evidence=evidence,
        )
    template = _effective_list_format(level)
    label, used = _expand_list_format(
        template, level_number, vector, style.levels, word_compatible=mso
    )
    if not label:
        raise ListNumberingUnsupported("label_empty")
    if level.position_mode != "label-alignment":
        # The printed gap is a fixed label width, not a character.
        raise ListNumberingUnsupported("label_width_and_position_mode")
    separator = _FOLLOWED_BY.get(level.followed_by)
    if separator is None:
        raise ListNumberingUnsupported("label_followed_by_unsupported")
    if any(target != level_number for target in used) and uncertain_ancestor:
        raise ListNumberingUnsupported("display_levels_phantom_ancestor")
    if mso:
        _check_word_format(level, styles, template)
        if counters is None:
            raise ListNumberingUnsupported("list_numbering_counters_missing")
        for target in used:
            if counters.get(target) != vector.get(target):
                raise ListNumberingUnsupported("list_numbering_models_disagree")
    evidence.update(
        {
            "number": vector.get(level_number),
            "list_format": template,
            "label_followed_by": level.followed_by,
            "start_value": level.start,
            "display_levels": level.display_levels,
            "restart": paragraph.restart,
        }
    )
    return ListLabel(
        status="labelled",
        label=label,
        separator=separator,
        export_prefix=indent + label + " ",
        evidence=evidence,
    )


def _check_word_format(level: _Level, styles: _Styles, template: str) -> None:
    """The Word list-format string must print the same template."""

    if level.word_format_name is None:
        return
    formats = styles.word_formats.get(level.word_format_name)
    if formats is None:
        raise ListNumberingUnsupported("word_list_format_malformed")
    if formats.get(level.level) != template:
        raise ListNumberingUnsupported("word_list_format_differs")


def document_generator(meta: ElementTree.Element | None) -> str:
    if meta is None:
        return ""
    node = meta.find(f".//{_TAG_GENERATOR}")
    return (node.text or "").strip() if node is not None else ""


def resolve_list_labels(
    content: ElementTree.Element,
    styles: ElementTree.Element | None = None,
    meta: ElementTree.Element | None = None,
) -> dict[int, ListLabel]:
    """Numbering of every paragraph that is in a list or may draw a number.

    The result maps ``id(element)`` of each affected ``text:p``/``text:h`` to
    its :class:`ListLabel`; paragraphs outside any list that draw nothing are
    absent.  ``content``/``styles``/``meta`` are the parsed ODF parts.
    """

    body = content.find(f".//{{{_OFFICE}}}text")
    if body is None:
        return {}
    resolved = _Styles(content, styles)
    mso = document_generator(meta).startswith(MSO_GENERATOR_PREFIX)
    walker = _Walker(resolved, mso=mso)
    walker.walk(body, None, False)
    result: dict[int, ListLabel] = dict(walker.outside)
    by_list: dict[str, list[_Paragraph]] = {}
    for paragraph in walker.paragraphs:
        by_list.setdefault(paragraph.list_id, []).append(paragraph)
    for paragraphs in by_list.values():
        tainted_from: int | None = None
        styles_used = {
            id(paragraph.style)
            for paragraph in paragraphs
            if paragraph.style is not None
        }
        if len(styles_used) > 1:
            tainted_from = -1
        for paragraph in paragraphs:
            if paragraph.taints_list and tainted_from is None:
                tainted_from = paragraph.order
        style = next(
            (paragraph.style for paragraph in paragraphs if paragraph.style),
            None,
        )
        real = [paragraph for paragraph in paragraphs if paragraph.source != "taint"]
        tree = _tree_numbers(real, style) if style is not None else {}
        counters = _counter_numbers(real, style) if style is not None else {}
        for paragraph in real:
            export_prefix = EXPORT_INDENT * (paragraph.level + 1)
            reason = paragraph.problem
            if reason is None and tainted_from is not None and (
                tainted_from < 0 or paragraph.order > tainted_from
            ):
                reason = "list_numbering_state_unsupported"
            if reason is None:
                vector, uncertain = tree[paragraph.order]
                try:
                    label = _label(
                        paragraph,
                        vector,
                        uncertain,
                        counters.get(paragraph.order),
                        resolved,
                        mso=mso,
                    )
                except ListNumberingUnsupported as exc:
                    reason = exc.reason
                else:
                    result[id(paragraph.element)] = label
                    continue
            result[id(paragraph.element)] = ListLabel(
                status="unsupported",
                export_prefix=export_prefix,
                reason=reason,
            )
    return result
