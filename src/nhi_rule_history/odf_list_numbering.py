def _embedded_containers(
    element: ElementTree.Element,
) -> Iterable[ElementTree.Element]:
    for child in element:
        if child.tag in {_TAG_NOTE, _TAG_ANNOTATION, _TAG_FRAME}:
            yield child
        elif child.tag not in {_TAG_P, _TAG_H}:
            yield from _embedded_containers(child)


class _Walker:
    """Replays LibreOffice's list-context stack over the document body."""

    def __init__(self, styles: _Styles, *, mso: bool) -> None:
        self.styles = styles
        self.mso = mso
        self.processed: dict[str, tuple[str, str]] = {}
        self.last_list_id = ""
        self.last_list_style: str | None = None
        self.style_last_list: dict[str, str] = {}
        self.generated = 0
        self.paragraphs: list[_Paragraph] = []
        self.outside: dict[int, ListLabel] = {}

    def _new_list_id(self) -> str:
        self.generated += 1
        return f"generated-list-{self.generated}"

    # LibreOffice keeps the list item on the list-context stack entry of the
    # innermost list block; a paragraph consumes it, a nested list's end and
    # an item's end clear it.
    def walk(
        self,
        node: ElementTree.Element,
        block: _Block | None,
        foreign: bool,
    ) -> None:
        for child in node:
            tag = child.tag
            if tag == _TAG_LIST:
                self._list(child, block, sub_list_index=0, foreign=foreign)
            elif tag in {_TAG_P, _TAG_H}:
                self._paragraph(child, block, foreign)
            elif tag == _TAG_NUMBERED_PARAGRAPH:
                self._numbered_paragraph(child, foreign)
            elif tag in {_TAG_NOTE, _TAG_ANNOTATION, _TAG_FRAME}:
                self.walk(child, None, True)
            else:
                self.walk(child, block, foreign)

    def _paragraph(
        self,
        element: ElementTree.Element,
        block: _Block | None,
        foreign: bool,
    ) -> None:
        if block is None:
            self._outside_list(element)
        else:
            self._list_paragraph(element, block)
        # Frames and notes anchored in a paragraph hold separate text.
        for container in _embedded_containers(element):
            self.walk(container, None, True)

    def _outside_list(self, element: ElementTree.Element) -> None:
        # Outline (chapter) numbering is not reproduced.  LibreOffice numbers
        # an outline-level heading even when its paragraph style is not
        # assigned to the outline, so any outline level that draws a label
        # is unsupported, as is a style chain assigned to such a level.
        if element.tag == _TAG_H and element.attrib.get(_ATTR_OUTLINE_LEVEL):
            if element.attrib.get(_ATTR_IS_LIST_HEADER) != "true" and (
                self.styles.outline_level_draws(
                    element.attrib.get(_ATTR_OUTLINE_LEVEL)
                )
            ):
                self.outside[id(element)] = ListLabel(
                    status="unsupported", reason="outline_number"
                )
            return
        if self.styles.outline_level_draws(
            self.styles.paragraph_outline_level(
                element.attrib.get(_ATTR_TEXT_STYLE)
            )
        ):
            self.outside[id(element)] = ListLabel(
                status="unsupported", reason="outline_number"
            )
            return
        named = self.styles.paragraph_list_style(
            element.attrib.get(_ATTR_TEXT_STYLE)
        )
        if named:
            # LibreOffice drops paragraph-style numbering outside a list;
            # the producing suite may not.
            self.outside[id(element)] = ListLabel(
                status="unsupported",
                reason="paragraph_style_numbering_outside_list",
            )

    def _list_paragraph(
        self, element: ElementTree.Element, block: _Block
    ) -> None:
        item = block.item
        counted = item is not None
        restart = False
        if block.restart:
            restart = True
            block.restart = False
        restart_value = item.start_value if item is not None else None
        if restart_value is not None:
            restart = True
        # Inside a list LibreOffice numbers with the list's style whatever
        # list style the paragraph style names.
        problem = block.problem
        taints = problem is not None
        if problem is None and element.tag == _TAG_H:
            problem = "heading_in_list"
        self.paragraphs.append(
            _Paragraph(
                element=element,
                order=len(self.paragraphs),
                list_id=block.continue_id or block.list_id,
                level=min(block.level, MAX_LEVELS - 1),
                counted=counted,
                restart=restart,
                restart_value=restart_value,
                style=block.style,
                problem=problem,
                taints_list=taints,
                source="list",
            )
        )
        block.item = None

    def _list(
        self,
        element: ElementTree.Element,
        parent: _Block | None,
        *,
        sub_list_index: int,
        foreign: bool,
    ) -> None:
        attributes = element.attrib
        continue_attribute = attributes.get(_ATTR_CONTINUE_NUMBERING)
        style_name = attributes.get(_ATTR_TEXT_STYLE)
        problem: str | None = None
        if foreign:
            problem = "list_in_frame_or_note"
        if parent is not None:
            restart = parent.restart or sub_list_index > 1
            if continue_attribute is not None:
                restart = continue_attribute != "true"
            name = parent.style_name if style_name is None else style_name
            if name != parent.style_name:
                problem = problem or "nested_list_style_differs"
            block = _Block(
                parent=parent,
                style_name=name,
                style=parent.style,
                level=parent.level + 1,
                list_id=parent.list_id,
                continue_id=parent.continue_id,
                restart=restart,
                problem=problem or parent.problem,
            )
            if block.level >= MAX_LEVELS:
                block.problem = block.problem or "list_level_too_deep"
        else:
            restart = (
                continue_attribute is not None and continue_attribute != "true"
            )
            style: _ListStyle | None = None
            if not style_name:
                # LibreOffice would invent a default rule.
                problem = problem or "list_style_missing"
            else:
                try:
                    style = self.styles.list_style(style_name)
                except ListNumberingUnsupported as exc:
                    problem = problem or exc.reason
            if style is not None and style.consecutive:
                problem = problem or "consecutive_numbering"
            list_id = attributes.get(_ATTR_XML_ID) or self._new_list_id()
            if self.processed.get(list_id, ("", ""))[0].startswith("numbered:"):
                problem = problem or "numbered_paragraph_list_shared"
            continue_id = attributes.get(_ATTR_CONTINUE_LIST, "")
            if continue_attribute is not None and not restart and not continue_id:
                if (
                    self.last_list_style == (style_name or "")
                    and self.last_list_id != list_id
                ):
                    continue_id = self.last_list_id
            if (
                not continue_id
                and continue_attribute is not None
                and not restart
                and self.mso
            ):
                continue_id = self.style_last_list.get(style_name or "", "")
            if continue_id:
                if continue_id not in self.processed:
                    continue_id = ""
                else:
                    master = self.processed[continue_id][1]
                    while master:
                        continue_id = master
                        master = self.processed[continue_id][1]
            if list_id not in self.processed:
                self.processed[list_id] = (style_name or "", continue_id)
                self.last_list_id = list_id
                self.last_list_style = style_name or ""
                self.style_last_list[style_name or ""] = list_id
            block = _Block(
                parent=None,
                style_name=style_name or "",
                style=style,
                level=0,
                list_id=list_id,
                continue_id=continue_id,
                restart=restart,
                problem=problem,
            )
        for child in element:
            if child.tag in {_TAG_LIST_ITEM, _TAG_LIST_HEADER}:
                self._item(child, block, foreign)
            elif child.tag != _TAG_SOFT_PAGE_BREAK:
                block.problem = block.problem or "unexpected_list_child"
                self._taint_later(block)
        if parent is not None:
            parent.restart = block.restart
            parent.item = None

    def _item(
        self, element: ElementTree.Element, block: _Block, foreign: bool
    ) -> None:
        header = element.tag == _TAG_LIST_HEADER
        start_value: int | None = None
        if not header and _ATTR_START in element.attrib:
            try:
                value = _int_attribute(element.attrib[_ATTR_START])
            except ValueError:
                value = None
                block.problem = block.problem or "list_item_attribute"
            if value is not None and 0 <= value <= _SHRT_MAX:
                start_value = value
        if _ATTR_STYLE_OVERRIDE in element.attrib:
            block.problem = block.problem or "list_item_style_override"
        if not header:
            block.item = _Item(start_value=start_value)
        sub_lists = 0
        for child in element:
            if child.tag in {_TAG_P, _TAG_H}:
                self._paragraph(child, block, foreign)
            elif child.tag == _TAG_LIST:
                sub_lists += 1
                self._list(child, block, sub_list_index=sub_lists, foreign=foreign)
            elif child.tag != _TAG_SOFT_PAGE_BREAK:
                block.problem = block.problem or "unexpected_list_item_child"
                self._taint_later(block)
        block.item = None

    def _taint_later(self, block: _Block) -> None:
        self.paragraphs.append(
            _Paragraph(
                element=ElementTree.Element("taint"),
                order=len(self.paragraphs),
                list_id=block.continue_id or block.list_id,
                level=0,
                counted=False,
                restart=False,
                restart_value=None,
                style=block.style,
                problem=block.problem,
                taints_list=True,
                source="taint",
            )
        )

    def _numbered_paragraph(
        self, element: ElementTree.Element, foreign: bool
    ) -> None:
        """``text:numbered-paragraph`` with an explicit list id and style."""

        problem: str | None = "list_in_frame_or_note" if foreign else None
        list_id = element.attrib.get(_ATTR_LIST_ID, "")
        style_name = element.attrib.get(_ATTR_TEXT_STYLE, "")
        style: _ListStyle | None = None
        level = 0
        start_value: int | None = None
        try:
            parsed_level = _int_attribute(element.attrib.get(_ATTR_LEVEL))
            parsed_start = _int_attribute(element.attrib.get(_ATTR_START))
        except ValueError:
            parsed_level, parsed_start = None, None
            problem = problem or "numbered_paragraph_attribute"
        if parsed_level is not None and parsed_level >= 1:
            level = parsed_level - 1
        if parsed_start is not None and 0 <= parsed_start <= _SHRT_MAX:
            start_value = parsed_start
        if not list_id or not style_name:
            # Without both, LibreOffice derives the list from per-level state.
            problem = problem or "numbered_paragraph_without_list_id_or_style"
        else:
            try:
                style = self.styles.list_style(style_name)
            except ListNumberingUnsupported as exc:
                problem = problem or exc.reason
            known = self.processed.get(list_id)
            if known is not None and known[0] != f"numbered:{style_name}":
                problem = problem or "numbered_paragraph_list_shared"
            self.processed.setdefault(list_id, (f"numbered:{style_name}", ""))
        if level >= MAX_LEVELS:
            problem = problem or "list_level_too_deep"
        paragraphs = [
            child for child in element if child.tag in {_TAG_P, _TAG_H}
        ]
        if len(paragraphs) != 1 or len(paragraphs) != len(
            [child for child in element if child.tag != _TAG_SOFT_PAGE_BREAK]
        ):
            problem = problem or "numbered_paragraph_content"
        for child in paragraphs:
            self.paragraphs.append(
                _Paragraph(
                    element=child,
                    order=len(self.paragraphs),
                    list_id=f"numbered:{list_id}",
                    level=level,
                    counted=True,
                    restart=start_value is not None,
                    restart_value=start_value,
                    style=style,
                    problem=problem
                    or ("heading_in_list" if child.tag == _TAG_H else None),
                    taints_list=problem is not None,
                    source="numbered-paragraph",
                )
            )


